/** Translates a screen text into the chosen language (texts without a translation stay English). */
fun tr(s: String): String {
    val d = when (Lang.code) { "bn" -> BN; else -> return s }
    d[s]?.let { return it }
    Regex("^(.*) \\((\\d+)\\)$").find(s)?.let { m -> d[m.groupValues[1]]?.let { return "$it (${m.groupValues[2]})" } }
    return d[s.replace('…', '.').trimEnd('.')] ?: s
}

